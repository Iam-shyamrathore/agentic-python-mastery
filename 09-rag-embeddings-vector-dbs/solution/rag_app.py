# ===========================================================================
# EDUCATIONAL ARCHITECTURE GUIDE: Advanced RAG Engineering Concepts
# ===========================================================================
# 1. EMBEDDING DRIFT & VECTOR SPACE INCOMPATIBILITY:
#    Embedding models (e.g. OpenAI text-embedding-3-small, BGE, Cohere) map text
#    into a high-dimensional vector space (e.g. 1536 or 768 dimensions).
#    CRITICAL PITFALL: If you upgrade your embedding model from Model A to Model B,
#    you CANNOT query existing vectors generated by Model A!
#    Even minor model checkpoints alter the coordinate topology.
#    In production, you must:
#    a. Persist original raw text and chunk boundaries alongside vectors.
#    b. Version your vector collections (e.g. 'kb_v1_bge_small', 'kb_v2_openai3').
#    c. Implement blue-green re-indexing pipelines when switching models.
#    d. Monitor Domain Drift: As new industry terminology or internal project codenames
#       emerge, static embeddings may experience semantic degradation, requiring fine-tuning.
#
# 2. DENSE VS. SPARSE RETRIEVAL & HYBRID SEARCH:
#    - Dense Retrieval (Bi-encoder Embeddings):
#      Encodes semantic intent into continuous vectors. Excels at concept matching
#      ("puppy care" matches "dog nutrition") and cross-lingual retrieval.
#      WEAKNESS: Fails on exact serial numbers, error codes ("ERR_404_TIMEOUT"),
#      short acronyms, and rare proper nouns.
#    - Sparse Retrieval (BM25 / TF-IDF / SPLADE):
#      Matches exact lexical terms based on term frequency and inverted indices.
#      WEAKNESS: Blind to synonyms and semantic relationships.
#    - Hybrid Search (Dense + Sparse Fusion):
#      Production systems execute both in parallel and fuse rankings using
#      Reciprocal Rank Fusion (RRF):
#          RRF_Score(doc) = Sum(1 / (k + rank_dense(doc)) + 1 / (k + rank_sparse(doc)))
#      where k is a constant smoothing factor (typically k=60).
#    - Re-Ranking Stage:
#      A heavy Cross-Encoder model (e.g., Cohere Rerank, BGE-Reranker-Large) scores
#      the top 25 hybrid candidates jointly with the query to produce the final top-3 chunks.
#
# 3. GROUNDED PROMPT ENGINEERING & CITATION INTEGRITY:
#    - Negative Constraint: Explicitly instruct the LLM: "Answer ONLY using the provided context.
#      If the context does not contain the answer, state that you do not know."
#    - Attribution Requirement: Force the LLM to tag claims with chunk IDs like `[doc_id_chunk_0]`.
#    - Zero Temperature: Set `temperature=0.0` to minimize token variance on factual Q&A tasks.
# ===========================================================================


@dataclass
class TextChunk:
    """Represents an extracted chunk of text with metadata and vector distance."""

    chunk_id: str
    text: str
    metadata: dict[str, Any]
    distance: float | None = None


# ---------------------------------------------------------------------------
# Boundary-Aware Semantic Chunker
# ---------------------------------------------------------------------------
def chunk_text(
    text: str,
    chunk_size: int = 200,
    chunk_overlap: int = 50,
) -> list[str]:
    """Split text into boundary-aware overlapping chunks without truncating words.
    
    Educational Engineering Note:
    ------------------------------
    Hard character slicing (`text[i:i+N]`) cuts words in half (e.g., 'intelligence'
    becoming 'intel' and 'ligence'), destroying token boundaries and distorting
    embedding representations.
    
    This implementation searches backwards from the target window end to locate
    natural semantic boundaries in descending order of priority:
    1. Paragraph breaks (`\\n\\n`)
    2. Line breaks (`\\n`)
    3. Sentence terminators (`. `, `! `, `? `)
    4. Clause delimiters (`; `, `, `)
    5. Word boundaries (` `)
    
    Args:
        text: Source text to split.
        chunk_size: Maximum character length per chunk.
        chunk_overlap: Target character overlap between consecutive chunks.
        
    Returns:
        List of clean, coherent chunk strings.
    """
    if not text or not text.strip():
        return []
    if chunk_size <= chunk_overlap:
        raise ValueError("chunk_size must be strictly greater than chunk_overlap.")

    text = text.strip()
    text_len = len(text)
    chunks: list[str] = []
    start = 0

    BOUNDARIES = ["\n\n", "\n", ". ", "! ", "? ", "; ", ", ", " "]

    while start < text_len:
        # If remaining text fits within one chunk, consume it completely
        if text_len - start <= chunk_size:
            final_chunk = text[start:].strip()
            if final_chunk:
                chunks.append(final_chunk)
            break

        candidate_end = start + chunk_size
        sub = text[start:candidate_end]

        # Scan for best boundary in the latter half of the window
        min_split = max(chunk_overlap, int(chunk_size * 0.4))
        split_pos = -1

        for b in BOUNDARIES:
            pos = sub.rfind(b)
            if pos >= min_split:
                if b in (". ", "! ", "? "):
                    split_pos = pos + 1  # Preserve the punctuation
                elif b in ("; ", ", "):
                    split_pos = pos + 1
                else:
                    split_pos = pos
                break

        if split_pos == -1:
            # Fallback if no clean boundary is found (e.g. continuous URL or string)
            split_pos = chunk_size

        chunk = text[start : start + split_pos].strip()
        if chunk:
            chunks.append(chunk)

        # Calculate next start point respecting overlap
        next_start = start + split_pos - chunk_overlap

        # If next_start splits inside a word, snap to the start of the word
        if 0 < next_start < text_len and text[next_start].isalpha() and text[next_start - 1].isalpha():
            prev_space = text.rfind(" ", start, next_start)
            if prev_space > start:
                next_start = prev_space + 1

        # Guarantee strict forward progress to prevent infinite loops
        if next_start <= start:
            next_start = start + max(1, split_pos)
        start = next_start

    return chunks


# ---------------------------------------------------------------------------
# RAG Engine with Metadata & Threshold Filtering
# ---------------------------------------------------------------------------
class RAGEngine:
    """Document Q&A engine using ChromaDB with metadata filtering,
    similarity threshold filtering, and grounded LLM context synthesis.
    """

    def __init__(self, collection_name: str = "rag_knowledge") -> None:
        self.chroma_client = chromadb.Client()
        self.collection = self.chroma_client.get_or_create_collection(
            name=collection_name,
            metadata={"hnsw:space": "cosine"},
        )
        logger.info("Initialized ChromaDB collection: '%s' (cosine space)", collection_name)

    def ingest_document(
        self,
        doc_id: str,
        text: str,
        metadata: dict[str, Any] | None = None,
        chunk_size: int = 200,
        chunk_overlap: int = 50,
    ) -> int:
        """Chunk and ingest a text document into ChromaDB with metadata preservation.
        
        Args:
            doc_id: Unique identifier for the parent document.
            text: Raw document text content.
            metadata: Optional dictionary of key-value attributes (e.g. category, author, tenant).
            chunk_size: Maximum character length per chunk.
            chunk_overlap: Overlap length between chunks.
            
        Returns:
            Count of successfully ingested chunks.
        """
        chunks = chunk_text(text, chunk_size=chunk_size, chunk_overlap=chunk_overlap)
        if not chunks:
            logger.warning("Document '%s' produced 0 chunks (empty or invalid text)", doc_id)
            return 0

        meta_base = metadata or {}
        ids = [f"{doc_id}_chunk_{i}" for i in range(len(chunks))]
        metadatas = [
            {**meta_base, "doc_id": doc_id, "chunk_index": i}
            for i in range(len(chunks))
        ]

        self.collection.add(
            documents=chunks,
            metadatas=metadatas,
            ids=ids,
        )
        logger.info("Ingested document '%s': %d chunks indexed", doc_id, len(chunks))
        return len(chunks)

    def retrieve(
        self,
        query: str,
        top_k: int = 3,
        where: dict[str, Any] | None = None,
        max_distance: float | None = 0.8,
    ) -> list[TextChunk]:
        """Query ChromaDB with optional metadata filtering and similarity threshold filtering.
        
        Educational Engineering Note:
        ------------------------------
        1. Metadata Filtering (`where={"category": "database"}`):
           Allows pre-filtering vectors based on tenant_id, security clearance,
           or document domain before distance computation.
        2. Similarity Threshold Filtering (`max_distance=0.8`):
           In Cosine distance, 0 is identical, 1 is orthogonal, and 2 is opposite.
           Chunks with cosine distance > 0.8 are essentially random semantic noise.
           Filtering them prevents irrelevant context from polluting the LLM's prompt,
           dramatically reducing hallucinations.
        
        Args:
            query: Natural language query string.
            top_k: Maximum number of closest candidate chunks to retrieve.
            where: Metadata filter dictionary (e.g. `{"category": "database"}`).
            max_distance: Maximum allowable cosine distance (drops chunks with distance > max_distance).
            
        Returns:
            Filtered list of TextChunk objects sorted by relevance.
        """
        query_kwargs: dict[str, Any] = {
            "query_texts": [query],
            "n_results": top_k,
        }
        if where:
            query_kwargs["where"] = where

        logger.debug("Querying vector DB - query: '%s', top_k: %d, where: %s", query, top_k, where)
        results = self.collection.query(**query_kwargs)

        matched_chunks: list[TextChunk] = []
        if results and results.get("documents") and results["documents"][0]:
            docs = results["documents"][0]
            ids = results["ids"][0]
            metas = results["metadatas"][0] if results.get("metadatas") else [{}] * len(docs)
            dists = results["distances"][0] if results.get("distances") and results["distances"] else [None] * len(docs)

            for doc_text, cid, meta, dist in zip(docs, ids, metas, dists):
                # Similarity Threshold Filtering
                if max_distance is not None and dist is not None and dist > max_distance:
                    logger.debug(
                        "Dropping chunk '%s' due to distance %.3f exceeding threshold %.2f",
                        cid,
                        dist,
                        max_distance,
                    )
                    continue

                matched_chunks.append(
                    TextChunk(
                        chunk_id=cid,
                        text=doc_text,
                        metadata=meta,
                        distance=dist,
                    )
                )

        logger.info("Retrieved %d relevant chunks for query: '%s'", len(matched_chunks), query)
        return matched_chunks

    def answer_query(
        self,
        query: str,
        top_k: int = 3,
        where: dict[str, Any] | None = None,
        max_distance: float | None = 0.8,
    ) -> dict[str, Any]:
        """Retrieve relevant context and synthesize a grounded answer with citations.
        
        Args:
            query: User's question.
            top_k: Number of chunks to retrieve.
            where: Optional metadata filter.
            max_distance: Cosine distance threshold filter.
            
        Returns:
            Dictionary containing 'query', 'answer', and 'sources'.
        """
        retrieved_chunks = self.retrieve(query, top_k=top_k, where=where, max_distance=max_distance)

        # Grounded Guardrail: If no chunks pass similarity threshold, refuse to hallucinate
        if not retrieved_chunks:
            logger.info("No context chunks met threshold for query '%s'", query)
            return {
                "query": query,
                "answer": "No relevant context found in knowledge base.",
                "sources": [],
            }

        context_str = "\n\n".join(
            [f"--- Document Source [{c.chunk_id}] ---\n{c.text}" for c in retrieved_chunks]
        )

        system_instruction = (
            "You are a strict, factual QA assistant. Answer the user query ONLY using the provided "
            "context snippets. If the context does not contain enough information to answer, state clearly "
            "that you do not know. Every factual assertion MUST cite its source like [doc_id_chunk_0]."
        )

        # Multi-provider LLM invocation or grounded reference fallback
        groq_key = os.getenv("GROQ_API_KEY")
        openai_key = os.getenv("OPENAI_API_KEY")

        if groq_key or openai_key:
            from openai import OpenAI
            client = (
                OpenAI(base_url="https://api.groq.com/openai/v1", api_key=groq_key)
                if groq_key
                else OpenAI(api_key=openai_key)
            )
            model = "llama-3.3-70b-versatile" if groq_key else "gpt-4o-mini"
            messages = [
                {"role": "system", "content": f"{system_instruction}\n\nContext:\n{context_str}"},
                {"role": "user", "content": query},
            ]
            resp = client.chat.completions.create(model=model, messages=messages, temperature=0.0)
            answer_text = resp.choices[0].message.content or ""
        else:
            # Deterministic, citation-preserving answer for offline/test environments
            primary_chunk = retrieved_chunks[0]
            answer_text = (
                f"Grounded Answer: According to [{primary_chunk.chunk_id}], "
                f"{primary_chunk.text.strip()}"
            )

        return {
            "query": query,
            "answer": answer_text,
            "sources": [c.chunk_id for c in retrieved_chunks],
        }


