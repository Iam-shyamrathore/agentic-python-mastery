# CLI Entrypoint
# ---------------------------------------------------------------------------
def main() -> None:
    parser = argparse.ArgumentParser(description="Document Q&A RAG Engine")
    parser.add_argument("query", nargs="?", default="What features make LangGraph suitable for agents?")
    parser.add_argument("--category", help="Optional metadata filter by category")
    args = parser.parse_args()

    engine = RAGEngine()

    # Ingest sample knowledge base with rich metadata
    doc1 = (
        "FastAPI is a modern, high-performance web framework for building APIs with Python 3.8+ "
        "based on standard Python type hints. It provides automatic interactive Swagger documentation "
        "and is built on top of Starlette and Pydantic."
    )
    doc2 = (
        "LangGraph is a specialized orchestration library for building stateful, multi-actor agent workflows with LLMs. "
        "Unlike linear chains, LangGraph natively supports cyclical graphs, conditional branching, human-in-the-loop "
        "breakpoints, and persistent state checkpoints."
    )
    doc3 = (
        "ChromaDB is an open-source, AI-native embedding database. It allows storing embeddings, document texts, "
        "and rich metadata with built-in HNSW vector indexing for millisecond similarity search."
    )

    engine.ingest_document("fastapi_guide", doc1, metadata={"category": "backend", "level": "intermediate"})
    engine.ingest_document("langgraph_guide", doc2, metadata={"category": "agents", "level": "advanced"})
    engine.ingest_document("chroma_guide", doc3, metadata={"category": "database", "level": "beginner"})

    where_filter = {"category": args.category} if args.category else None
    print(f"🔍 Asking RAG Engine: '{args.query}' (filter: {where_filter})\n")

    response = engine.answer_query(args.query, where=where_filter)
    print(f"💡 Grounded Answer:\n{response['answer']}\n")
    print(f"📑 Sources Cited: {response['sources']}")


if __name__ == "__main__":
    main()
