# Unified Multi-Provider LLM Client
# ---------------------------------------------------------------------------
class UnifiedLLMClient:
    """Production-grade multi-provider LLM client with automatic key detection,
    structured outputs, streaming, token tracking, prompt caching design,
    and resilient error handling.
    """

    def __init__(
        self,
        provider: str | None = None,
        model: str | None = None,
    ) -> None:
        groq_key = os.getenv("GROQ_API_KEY")
        openrouter_key = os.getenv("OPENROUTER_API_KEY")
        openai_key = os.getenv("OPENAI_API_KEY")

        if provider == "groq" or (provider is None and groq_key):
            self.provider = "groq"
            self.model = model or "llama-3.3-70b-versatile"
            self.client = OpenAI(
                base_url="https://api.groq.com/openai/v1",
                api_key=groq_key or "dummy_key",
            )
        elif provider == "openrouter" or (provider is None and openrouter_key):
            self.provider = "openrouter"
            self.model = model or "meta-llama/llama-3.2-3b-instruct:free"
            self.client = OpenAI(
                base_url="https://openrouter.ai/api/v1",
                api_key=openrouter_key or "dummy_key",
            )
        elif provider == "openai" or (provider is None and openai_key):
            self.provider = "openai"
            self.model = model or "gpt-4o-mini"
            self.client = OpenAI(api_key=openai_key or "dummy_key")
        else:
            # Fallback to local Ollama (zero API key cost)
            self.provider = "ollama"
            self.model = model or "llama3.2:3b"
            self.client = OpenAI(
                base_url=os.getenv("OLLAMA_BASE_URL", "http://localhost:11434/v1"),
                api_key="ollama",
            )

        self.last_usage: TokenUsage | None = None
        self.cumulative_usage: TokenUsage = TokenUsage()
        logger.info("Initialized UnifiedLLMClient [provider=%s, model=%s]", self.provider, self.model)

    def _record_usage(
        self,
        prompt_text: str,
        completion_text: str,
        raw_usage: Any | None = None,
    ) -> TokenUsage:
        """Extract exact token usage from API response or estimate via fallback."""
        if raw_usage is not None and getattr(raw_usage, "total_tokens", 0):
            usage = TokenUsage(
                prompt_tokens=getattr(raw_usage, "prompt_tokens", 0) or 0,
                completion_tokens=getattr(raw_usage, "completion_tokens", 0) or 0,
                total_tokens=getattr(raw_usage, "total_tokens", 0) or 0,
                estimated=False,
            )
        else:
            p_tok = estimate_tokens(prompt_text, self.model)
            c_tok = estimate_tokens(completion_text, self.model)
            usage = TokenUsage(
                prompt_tokens=p_tok,
                completion_tokens=c_tok,
                total_tokens=p_tok + c_tok,
                estimated=True,
            )

        self.last_usage = usage
        self.cumulative_usage.add(usage)
        logger.debug(
            "Tokens used - Prompt: %d, Completion: %d, Total: %d (Estimated: %s)",
            usage.prompt_tokens,
            usage.completion_tokens,
            usage.total_tokens,
            usage.estimated,
        )
        return usage

    @llm_retry_decorator
    def chat(
        self,
        prompt: str,
        system_prompt: str = "You are a helpful AI assistant.",
        temperature: float = 0.7,
    ) -> str:
        """Send chat completion with automatic retries and token metrics tracking.
        
        Args:
            prompt: User message prompt.
            system_prompt: Guiding system instructions.
            temperature: Sampling temperature (0.0=deterministic, 1.0=creative).
            
        Returns:
            The model's text response.
        """
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": prompt},
        ]

        logger.debug("Dispatching chat completion request to %s (%s)", self.provider, self.model)
        response = self.client.chat.completions.create(
            model=self.model,
            messages=messages,
            temperature=temperature,
        )

        content = response.choices[0].message.content or ""
        raw_usage = getattr(response, "usage", None)
        self._record_usage(system_prompt + prompt, content, raw_usage)
        return content

    def chat_stream(
        self,
        prompt: str,
        system_prompt: str = "You are a helpful AI assistant.",
        temperature: float = 0.7,
    ) -> Iterator[str]:
        """Stream response tokens incrementally for minimal Time-To-First-Token (TTFT).
        
        Educational Note on Streaming:
        ------------------------------
        In production user-facing applications (chatbots, agent consoles), users
        perceive latency based on TTFT rather than overall generation time. Streaming
        Server-Sent Events (SSE) provides immediate feedback even on 500-token completions.
        """
        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": prompt},
        ]

        stream = self.client.chat.completions.create(
            model=self.model,
            messages=messages,
            temperature=temperature,
            stream=True,
        )

        accumulated = []
        for chunk in stream:
            if not chunk.choices:
                continue
            delta = chunk.choices[0].delta.content
            if delta:
                accumulated.append(delta)
                yield delta

        full_content = "".join(accumulated)
        self._record_usage(system_prompt + prompt, full_content)

    @llm_retry_decorator
    def generate_plan(
        self,
        goal: str,
        enable_caching_hint: bool = True,
    ) -> TaskBreakdown:
        """Generate structured breakdown validated strictly against the TaskBreakdown Pydantic schema.
        
        Educational Note on Prompt Caching:
        -----------------------------------
        Prompt Caching (available in Anthropic via cache_control={'type': 'ephemeral'},
        Google Gemini Context Caching, and OpenAI Automatic Prefix Caching for >1024 tokens)
        caches the tokenized prefix of repetitive instructions.
        
        In production agent pipelines:
        1. Large schemas and few-shot examples (which can easily exceed 2,000-5,000 tokens)
           should be placed at the very start of the system prompt.
        2. Dynamic, per-turn data (user query, timestamps) is placed at the end.
        3. Result: Up to 90% cost reduction on input tokens and 80% reduction in TTFT latency!
        """
        schema_json = json.dumps(TaskBreakdown.model_json_schema(), indent=2)

        # Few-Shot Demonstrations accelerate model convergence to exact schema requirements
        few_shot_example = (
            "Example valid response format:\n"
            "{\n"
            '  "task_goal": "Setup Git Repository",\n'
            '  "difficulty": "Easy",\n'
            '  "steps": [\n'
            '    {"step_num": 1, "title": "Initialize", "description": "Run git init in workspace"}\n'
            "  ]\n"
            "}"
        )

        system_prompt = (
            "You are a principal technical project planner. You decompose engineering tasks into "
            "clear, atomic execution steps. You speak ONLY in valid JSON matching the exact schema.\n\n"
            f"REQUIRED JSON SCHEMA:\n{schema_json}\n\n"
            f"{few_shot_example}"
        )

        prompt = f"Decompose this engineering goal into a structured plan: '{goal}'"

        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": prompt},
        ]

        logger.info("Generating structured task plan for goal: '%s'", goal)
        response = self.client.chat.completions.create(
            model=self.model,
            messages=messages,
            response_format={"type": "json_object"},
            temperature=0.2,
        )

        raw_json = response.choices[0].message.content or "{}"
        raw_usage = getattr(response, "usage", None)
        self._record_usage(system_prompt + prompt, raw_json, raw_usage)

        try:
            return TaskBreakdown.model_validate_json(raw_json)
        except Exception as exc:
            logger.error("Failed to validate JSON response against TaskBreakdown: %s", exc)
            logger.debug("Raw payload was:\n%s", raw_json)
            raise


# ---------------------------------------------------------------------------
# CLI Entrypoint
# ---------------------------------------------------------------------------
def main() -> None:
    parser = argparse.ArgumentParser(description="Multi-Provider AI Text Assistant")
    parser.add_argument("prompt", nargs="?", default="Explain RAG in one short paragraph.")
    parser.add_argument("--stream", action="store_true", help="Stream response")
    parser.add_argument("--plan", action="store_true", help="Generate structured task plan")
    args = parser.parse_args()

    assistant = UnifiedLLMClient()
    print(f"🧠 Using Provider: [{assistant.provider}] with Model: [{assistant.model}]\n")

    if args.plan:
        print(f"📋 Generating structured plan for: '{args.prompt}'...")
        plan = assistant.generate_plan(args.prompt)
        print(f"\nGoal: {plan.task_goal} (Difficulty: {plan.difficulty})")
        for s in plan.steps:
            print(f"  Step {s.step_num}: {s.title} - {s.description}")
    elif args.stream:
        print("💬 Streaming response:")
        for token in assistant.chat_stream(args.prompt):
            print(token, end="", flush=True)
        print()
    else:
        result = assistant.chat(args.prompt)
        print(f"💬 Response:\n{result}")

    if assistant.last_usage:
        print(f"\n📊 Usage Metrics: {assistant.last_usage.total_tokens} total tokens "
              f"({assistant.last_usage.prompt_tokens} prompt, {assistant.last_usage.completion_tokens} completion)")


if __name__ == "__main__":
    main()
