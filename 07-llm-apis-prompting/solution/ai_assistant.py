# Token Usage & Estimation
# ---------------------------------------------------------------------------
class TokenUsage(BaseModel):
    """Tracks token consumption metrics for cost and context budget monitoring.
    
    Attributes:
        prompt_tokens: Tokens consumed by system instructions, history, and user input.
        completion_tokens: Tokens generated by the LLM in the response.
        total_tokens: Sum of prompt and completion tokens.
        estimated: True if values were approximated via tokenizer fallback.
    """

    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    estimated: bool = False

    def add(self, other: TokenUsage) -> None:
        """Accumulate usage from another invocation."""
        self.prompt_tokens += other.prompt_tokens
        self.completion_tokens += other.completion_tokens
        self.total_tokens += other.total_tokens


def estimate_tokens(text: str, model: str = "gpt-4o-mini") -> int:
    """Estimate token count using tiktoken with a deterministic character fallback.
    
    Educational Architecture Note:
    -------------------------------
    Why is token estimation critical in production agent loops?
    1. Context Window Exhaustion: Foundation models have hard context limits
       (e.g., 8k, 32k, 128k, 1M tokens). Exceeding this causes fatal 400 errors.
    2. Cost Guardrails: Pre-estimating tokens before dispatching allows billing checks
       and prevents runaway recursive agent loops from draining API budgets.
    3. TikToken vs Fallback: OpenAI models use Byte-Pair Encoding (cl100k_base or o200k_base).
       When tiktoken is unavailable or when non-OpenAI models (e.g. Llama 3 sentencepiece)
       are used, we use the industry-standard heuristic of ~4 characters per token
       for English text, while reserving safety margins.
    
    Args:
        text: The string to tokenize.
        model: Target model name for encoding lookup.
        
    Returns:
        Estimated integer number of tokens.
    """
    if not text:
        return 0

    try:
        import tiktoken

        try:
            encoding = tiktoken.encoding_for_model(model)
        except KeyError:
            # Fall back to cl100k_base (standard for GPT-4, Llama 3 token-approx)
            encoding = tiktoken.get_encoding("cl100k_base")
        return len(encoding.encode(text))
    except Exception as err:
        logger.debug("tiktoken lookup failed (%s); using 4 chars/token heuristic", err)
        # 1 token ~= 4 characters in English prose
        return max(1, (len(text) + 3) // 4)


